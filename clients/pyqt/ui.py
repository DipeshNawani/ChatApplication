        copy.addWidget(label(preview[:30] + ("…" if len(preview) > 30 else ""), "rowPreview"))
        row_layout.addLayout(copy, 1)
        item.setSizeHint(QSize(245, 68))
        item.setToolTip(name)
        self.room_list.setItemWidget(item, row)

