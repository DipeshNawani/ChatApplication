    def open_settings(self):
        dialog, layout = self._dialog("Connection settings", "Changing your server will sign you out.")
        layout.addWidget(label("Server address", "rowTitle"))
        field = QLineEdit(self.normalized_server_url())
        field.setAccessibleName("Server address")
        layout.addWidget(field)
        def save():
            if not field.text().strip():
                field.setFocus()
                return
            self.cancel_connection()
            self.server_url_input.setText(field.text().strip())
            save_settings(self.normalized_server_url(), self.current_username)
            self.token = ""
            self.clear_session()
            self.stack.setCurrentWidget(self.login_page)
            dialog.accept()
        actions = QHBoxLayout()
        actions.addStretch()
        actions.addWidget(self._button("Cancel", dialog.reject, "secondary"))
        actions.addWidget(self._button("Save changes", save))
        layout.addLayout(actions)
        dialog.exec()

