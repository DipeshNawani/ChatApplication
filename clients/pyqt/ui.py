        row_layout.addWidget(self._avatar("#" if room_id == "general" else initials(name)))
        copy = QVBoxLayout()
        copy.setSpacing(5)
        title = label(name, "rowTitle")
        title.setToolTip(name)
        copy.addWidget(title)
        messages = self.room_messages.get(room_id, [])
        last = messages[-1] if messages else None
        preview = (last.get("text") or (last.get("file") or {}).get("name") or "Attachment") if last else ("Everyone, together" if room_id == "general" else "Group conversation" if room_id.startswith("group-") else "Direct conversation")
